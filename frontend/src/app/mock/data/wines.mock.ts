// Helper functions for mock data
export function getWineById(id: string): Wine | undefined {
  return WINES.find(wine => wine.id === id);
}

export function getWineBySku(sku: string): Wine | undefined {
  return WINES.find(wine => wine.sku === sku);
}

export function getWinesByRegion(region: string): Wine[] {
  return WINES.filter(wine => wine.region.toLowerCase().includes(region.toLowerCase()));
}

export function getWinesByCountry(country: string): Wine[] {
  return WINES.filter(wine => wine.country.toLowerCase() === country.toLowerCase());
}

export function getWinesByGrape(grape: string): Wine[] {
  return WINES.filter(wine => wine.grapeVariety.toLowerCase().includes(grape.toLowerCase()));
}

export function getWinesByPriceRange(minBRL: number, maxBRL: number): Wine[] {
  return WINES.filter(wine => wine.prices.BRL >= minBRL && wine.prices.BRL <= maxBRL);
}

export function getGrapeVarieties(): string[] {
  return [...new Set(WINES.map(wine => wine.grapeVariety))].sort();
}

export function getRegions(): string[] {
  return [...new Set(WINES.map(wine => wine.region))].sort();
}

export function getCountries(): string[] {
  return [...new Set(WINES.map(wine => wine.country))].sort();
}

export function getVintages(): number[] {
  return [...new Set(WINES.map(wine => wine.vintage))].sort((a, b) => b - a);
}
